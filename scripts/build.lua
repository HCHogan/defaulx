-- Regenerate everything derived from lua/defaulx/palette/spec.lua:
--   lua/defaulx/palette/<variant>.lua   resolved hex palettes
--   lua/defaulx/revision.lua            hash of the sources, keys user caches
--   lua/defaulx/compiled/<variant>.lua  highlights for the default options
--
--   nvim --clean --headless -l scripts/build.lua           write the files
--   nvim --clean --headless -l scripts/build.lua --check   fail if any is stale

local root = vim.fs.dirname(vim.fs.dirname(vim.fs.normalize(vim.fn.fnamemodify(arg[0], ":p"))))
vim.opt.rtp:prepend(root)

local check = vim.list_contains(arg, "--check")
local color = require("defaulx.color")
local spec = require("defaulx.palette.spec")
local compile = require("defaulx.compile")

local function read(path)
  local fd = io.open(path, "rb")
  if not fd then
    return nil
  end
  local s = fd:read("*a")
  fd:close()
  return s
end

local stale = {}
local function emit(rel, content)
  local path = vim.fs.joinpath(root, rel)
  if read(path) == content then
    return
  end
  if check then
    stale[#stale + 1] = rel
    return
  end
  vim.fn.mkdir(vim.fs.dirname(path), "p")
  local fd = assert(io.open(path, "wb"))
  fd:write(content)
  fd:close()
  io.write("wrote " .. rel .. "\n")
end

---@param variant table spec.variants[name]
local function resolve(variant)
  local raw = vim.tbl_extend("error", variant.colors, variant.tints)
  local out, resolving = {}, {}
  local function get(v)
    if type(v) == "string" then
      if v:match("^#%x%x%x%x%x%x$") then
        return v:lower()
      end
      if out[v] then
        return out[v]
      end
      assert(raw[v], "unknown palette key " .. v)
      assert(not resolving[v], "palette cycle at " .. v)
      resolving[v] = true
      out[v] = get(raw[v])
      return out[v]
    elseif v.mix then
      return color.blend(get(v.mix[1]), get(v.mix[2]), v.mix[3])
    end
    return color.oklch(v[1], v[2], v[3])
  end
  for key in pairs(raw) do
    get(key)
  end
  local terminal = {}
  for i, v in ipairs(variant.terminal) do
    terminal[i] = get(v)
  end
  return out, terminal
end

local function serialize_palette(name, colors, terminal, background)
  local lines = {
    "-- Generated by scripts/build.lua from palette/spec.lua. Do not edit.",
    ("-- defaulx-%s"):format(name),
    "return {",
    ("  background = %q,"):format(background),
  }
  local keys = vim.tbl_keys(colors)
  table.sort(keys)
  for _, k in ipairs(keys) do
    lines[#lines + 1] = ("  %s = %q,"):format(k, colors[k])
  end
  lines[#lines + 1] = "  terminal = {"
  for _, c in ipairs(terminal) do
    lines[#lines + 1] = ("    %q,"):format(c)
  end
  lines[#lines + 1] = "  },"
  lines[#lines + 1] = "}"
  return table.concat(lines, "\n") .. "\n"
end

-- 1. palettes
local palettes, palette_sources = {}, {}
for _, name in ipairs(spec.order) do
  local variant = spec.variants[name]
  local colors, terminal = resolve(variant)
  local source = serialize_palette(name, colors, terminal, variant.background)
  emit(("lua/defaulx/palette/%s.lua"):format(name), source)
  palettes[name], palette_sources[name] = assert(load(source))(), source
end

-- 2. revision: every source file that can change the output. Palettes are
-- hashed from memory so --check agrees with a real build.
local sources = {}
for name, type in vim.fs.dir(vim.fs.joinpath(root, "lua/defaulx"), { depth = 10 }) do
  if type == "file" and name:match("%.lua$") and not name:match("^compiled/") and name ~= "revision.lua" then
    sources[#sources + 1] = name
  end
end
table.sort(sources)
local hashed = {}
for _, name in ipairs(sources) do
  local variant = name:match("^palette/(%a+)%.lua$")
  local content = palette_sources[variant] or read(vim.fs.joinpath(root, "lua/defaulx", name))
  hashed[#hashed + 1] = name .. "\0" .. content
end
local revision = vim.fn.sha256(table.concat(hashed, "\0")):sub(1, 16)
emit("lua/defaulx/revision.lua", ("-- Generated by scripts/build.lua. Do not edit.\nreturn %q\n"):format(revision))

-- 3. precompiled highlights for the default options
local defaults = require("defaulx.config").defaults
for _, name in ipairs(spec.order) do
  local data = compile.build(vim.deepcopy(palettes[name]), defaults)
  emit(("lua/defaulx/compiled/%s.lua"):format(name), compile.serialize(data))
end

if check then
  if #stale > 0 then
    -- selene: allow(incorrect_standard_library_use)
    io.stderr:write("stale generated files, run `nvim --clean --headless -l scripts/build.lua`:\n")
    for _, rel in ipairs(stale) do
      -- selene: allow(incorrect_standard_library_use)
      io.stderr:write("  " .. rel .. "\n")
    end
    os.exit(1)
  end
  io.write("generated files are up to date\n")
end
