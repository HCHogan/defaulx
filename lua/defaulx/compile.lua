---Turns options into highlight tables, through the precompiled files, the
---user cache, or a fresh build, in that order.
local M = {}

---@class defaulx.Compiled
---@field background "dark"|"light"
---@field groups table<string, vim.api.keyset.highlight>
---@field terminal string[]
---@field key? string cache key, absent in precompiled files

local function sorted_keys(t)
  local keys = vim.tbl_keys(t)
  table.sort(keys)
  return keys
end

local function lua_key(k)
  return k:match("^[%a_][%w_]*$") and k or ("[%q]"):format(k)
end

local function lua_value(v)
  return type(v) == "string" and ("%q"):format(v) or tostring(v)
end

---@param hl table
local function lua_table(hl)
  local parts = {}
  for _, k in ipairs(sorted_keys(hl)) do
    parts[#parts + 1] = lua_key(k) .. " = " .. lua_value(hl[k])
  end
  return #parts == 0 and "{}" or "{ " .. table.concat(parts, ", ") .. " }"
end

---Deterministic Lua source, so generated files diff cleanly.
---@param data defaulx.Compiled
---@return string
function M.serialize(data)
  local lines = { "-- Generated by scripts/build.lua. Do not edit.", "return {" }
  lines[#lines + 1] = ("  background = %q,"):format(data.background)
  if data.key then
    lines[#lines + 1] = ("  key = %q,"):format(data.key)
  end
  lines[#lines + 1] = "  groups = {"
  for _, name in ipairs(sorted_keys(data.groups)) do
    lines[#lines + 1] = ("    %s = %s,"):format(lua_key(name), lua_table(data.groups[name]))
  end
  lines[#lines + 1] = "  },"
  lines[#lines + 1] = "  terminal = {"
  for _, color in ipairs(data.terminal) do
    lines[#lines + 1] = ("    %q,"):format(color)
  end
  lines[#lines + 1] = "  },"
  lines[#lines + 1] = "}"
  return table.concat(lines, "\n") .. "\n"
end

---@param palette defaulx.Palette
---@param opts defaulx.Options
---@return defaulx.Compiled
function M.build(palette, opts)
  local c = require("defaulx.theme")(palette)
  return {
    background = palette.background,
    groups = require("defaulx.groups").get(c, opts),
    terminal = palette.terminal,
  }
end

local function cache_path(variant)
  return vim.fs.joinpath(vim.fn.stdpath("cache") --[[@as string]], "defaulx", variant .. ".luac")
end

local function cache_key(variant, opts, palette)
  return vim.fn.sha256(vim.inspect({
    revision = require("defaulx.revision"),
    variant = variant,
    transparent = opts.transparent,
    styles = opts.styles,
    plugins = opts.plugins,
    palette = palette,
  }))
end

---@return defaulx.Compiled?
local function read_cache(path, key)
  local chunk = loadfile(path)
  if not chunk then
    return
  end
  local ok, data = pcall(chunk)
  if ok and type(data) == "table" and data.key == key then
    return data
  end
end

local function write_cache(path, data)
  vim.fn.mkdir(vim.fs.dirname(path), "p")
  local chunk = assert(load(M.serialize(data), "=defaulx"))
  local fd = io.open(path, "wb")
  if fd then
    -- selene: allow(incorrect_standard_library_use)
    fd:write(string.dump(chunk, true))
    fd:close()
  end
end

---@param variant string
---@param opts defaulx.Options
---@return defaulx.Compiled
function M.get(variant, opts)
  local palettes = require("defaulx.palette")
  if require("defaulx.config").is_precompiled(opts) then
    palettes.get(variant) -- validates the name
    return require("defaulx.compiled." .. variant)
  end

  local palette = palettes.get(variant)
  if opts.on_palette then
    opts.on_palette(palette, variant)
  end
  if not opts.cache then
    return M.build(palette, opts)
  end

  local path, key = cache_path(variant), cache_key(variant, opts, palette)
  local data = read_cache(path, key)
  if not data then
    data = M.build(palette, opts)
    data.key = key
    write_cache(path, data)
  end
  return data
end

---Remove cached highlights, e.g. after editing `on_palette`.
function M.clear_cache()
  vim.fn.delete(vim.fs.joinpath(vim.fn.stdpath("cache") --[[@as string]], "defaulx"), "rf")
end

return M
